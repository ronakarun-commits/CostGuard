"""Reproduce docs/evaluation.md: detector scores and risk-model backtests on several seeds.

    uv run python scripts/evaluate.py > docs/evaluation.md
"""

from __future__ import annotations

import statistics
import sys
from datetime import date

from costguard.core.analytics.anomaly import METHODS, detect, evaluate
from costguard.core.analytics.risk import kupiec_pof, month_end_backtest, var_backtest
from costguard.providers.synthetic import SyntheticProvider
from costguard.storage.duckdb_repo import DuckDBRepository

SEEDS = (42, 7, 123, 2024, 99)


def main() -> None:
    det: dict[str, list[tuple[float, float, float, float]]] = {m: [] for m in METHODS}
    risk_rows = []
    for seed in SEEDS:
        p = SyntheticProvider(date(2025, 10, 10), 365, seed=seed)
        with DuckDBRepository() as repo:
            repo.upsert_costs(p.get_costs(p.world), "synthetic")
            costs = repo.costs_frame()
            series = repo.daily_series()["cost"]
        labels = p.get_anomalies(p.world)
        for m in METHODS:
            e = evaluate(detect(costs, m), labels, m)
            det[m].append((e.precision, e.recall, e.f1, e.mean_delay_days or 0.0))
        df, cal = var_backtest(series)
        raw = kupiec_pof(int((df["actual"] > df["raw_bound"]).sum()), len(df), 0.05)
        mb_raw = month_end_backtest(series, calibrate=False)
        mb_cal = month_end_backtest(series, calibrate=True)
        risk_rows.append((seed, len(labels), raw, cal, mb_raw, mb_cal))
        print(f"seed {seed} done", file=sys.stderr)

    out = ["# Evaluation", "",
           f"Generated by `scripts/evaluate.py` on {len(SEEDS)} synthetic organisations (seeds "
           f"{', '.join(map(str, SEEDS))}), 365 days each, 4 accounts, 26 account×service series.",
           "", "## Anomaly detectors (event-level, mean over seeds)", "",
           "| Method | Precision | Recall | F1 | Mean delay (days) | Causal? |",
           "|---|---|---|---|---|---|"]  # fmt: skip
    causal = {"baseline": "yes", "stl": "no (in-sample)", "iforest": "features yes, fit no"}
    for m, rows in det.items():
        p, r, f, d = (statistics.mean(x[i] for x in rows) for i in range(4))
        out.append(f"| {m} | {p:.0%} | {r:.0%} | {f:.0%} | {d:.1f} | {causal[m]} |")
    out += ["", "## Risk model backtests (ETS, 95% daily upper bounds)", "",
            "| Seed | Labels | Raw exceedances | Raw Kupiec p | Calibrated exceedances | "
            "Calibrated Kupiec p | Month-end MAPE | 90% coverage raw → calibrated |",
            "|---|---|---|---|---|---|---|---|"]  # fmt: skip
    for seed, n, raw, cal, mr, mc in risk_rows:
        out.append(
            f"| {seed} | {n} | {raw.observed_rate:.1%} | {raw.p_value:.3g} | "
            f"{cal.observed_rate:.1%} | {cal.p_value:.3g} | {mc.mape:.1%} | "
            f"{mr.coverage:.0%} → {mc.coverage:.0%} |"
        )
    print("\n".join(out))


if __name__ == "__main__":
    main()
